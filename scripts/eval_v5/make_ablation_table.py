#!/usr/bin/env python3
"""Supplementary table and macros for the targeted PanNuke-exposure ablation (analysis plan 7.2)
from outputs/v5_ablation/no_pannuke/compare.json (written by compare_ablation.py).
Writes paper_jbhi/supplement/tables/s_ablation.tex and paper_jbhi/macros_ablation.tex."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "outputs/v5_ablation/no_pannuke/compare.json"
NAME = {"h-optimus-0": "H-optimus-0", "phikon": "Phikon"}
MACRO = {"h-optimus-0": "Hopt", "phikon": "Phikon"}
TASKS = [("pannuke_seg", "PanNuke Dice (primary)"), ("c16", "CAMELYON16"), ("c17_loco", "CAMELYON17-LOCO"),
         ("panda", "PANDA tiles"), ("panda_biopsy_tissue", "PANDA biopsies (tissue)"),
         ("panda_biopsy", "PANDA biopsies (annotated)"), ("msi", "Kather-MSI"), ("center", "TCGA site"),
         ("crc7k", "CRC-VAL-HE-7K")]
WORD = {7: "seven", 8: "eight"}
SHORT = {"equivalent": "E", "inequivalent": "N", "inconclusive": "I"}


def controls(r):
    n = sum(k in r for k, _ in TASKS[1:]); e = sum(r[k]["state"] == "equivalent" for k, _ in TASKS[1:] if k in r)
    return f"all {WORD.get(n, n)}" if e == n else f"{e} of {n}"


def main():
    res = json.load(open(SRC))
    rows, mac = [], []
    for t in [k for k in NAME if k in res]:
        r = res[t]
        for i, (task, label) in enumerate(TASKS):
            if task not in r:
                continue
            v = r[task]
            orig = v.get("dice_original", v.get("metric_original")); abl = v.get("dice_ablated", v.get("metric_ablated"))
            rows.append(f"{NAME[t] if i == 0 else ''} & {label} & {orig:.3f} & {abl:.3f} & "
                        f"{v['d_abl_vs_orig']:+.4f} [{v['lo']:+.4f}, {v['hi']:+.4f}] & {SHORT[v['state']]} & "
                        f"{SHORT[v['teacher_verdict_ablated']]}\\\\")
        rows.append("\\midrule")
        p = r["pannuke_seg"]; m = MACRO[t]
        mac += [f"\\newcommand{{\\abl{m}D}}{{{p['d_abl_vs_orig']:.3f}}}",
                f"\\newcommand{{\\abl{m}CI}}{{$[{p['lo']:.3f},{p['hi']:.3f}]$}}",
                f"\\newcommand{{\\abl{m}Orig}}{{{p['dice_original']:.3f}}}",
                f"\\newcommand{{\\abl{m}Abl}}{{{p['dice_ablated']:.3f}}}",
                f"\\newcommand{{\\abl{m}State}}{{{p['state']}}}",
                f"\\newcommand{{\\abl{m}Controls}}{{{controls(r)}}}"]
    rows = rows[:-1]
    tex = [r"\begin{table}[h]\centering\footnotesize\setlength{\tabcolsep}{3pt}",
           r"\caption{Targeted PanNuke-exposure ablation (not pre-specified): ViT-B student, seed 42, "
           r"distilled with the PanNuke tiles removed from the corpus and otherwise the identical recipe, against the original "
           r"student of the same teacher, size and seed. $d_{\mathrm{abl}}$ = metric(ablated) $-$ metric(original) with paired "
           r"90\,\% bootstrap interval (per image for PanNuke, per cluster otherwise), verdict at $\delta=0.05$; last column, "
           r"the ablated student's own verdict against its teacher. E equivalent, N inequivalent, I inconclusive.}\label{tab:s_ablation}",
           r"\begin{tabular}{@{}llrrlcc@{}}", r"\toprule",
           r"Teacher & Task & Original & Ablated & $d_{\mathrm{abl}}$ [90\,\% CI] & Abl.\ vs orig. & Abl.\ vs teacher\\",
           r"\midrule", *rows, r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    (ROOT / "paper_jbhi/supplement/tables/s_ablation.tex").write_text("\n".join(tex) + "\n")
    (ROOT / "paper_jbhi/macros_ablation.tex").write_text("% generated by scripts/eval_v5/make_ablation_table.py\n" + "\n".join(mac) + "\n")


if __name__ == "__main__":
    main()
